/**
 * Regenerates src/utils/certificate-assets/headings.ts.
 *
 * The certificate's heading is drawn as outlines rather than set in a font,
 * because the face it uses is licensed: it can be neither embedded in the
 * output nor assumed installed wherever a certificate is rendered. The
 * original asset (heading.ts, now replaced) was traced by hand out of the
 * printed design, which fixed it at the one string the designer had set -
 * "Certificate of Completion". That is true of the students who finished a
 * programme and of nobody else, and the traced glyphs were C a c e f i l m n
 * o p r t, with no A for "Appreciation" and no R for "Recognition", so the
 * wording could not be changed without tracing more.
 *
 * This traces them instead, from a font file on the machine that runs it, and
 * writes out one set of outlines per heading the achievement schema allows.
 * Only the outlines are committed - the same thing the design already shipped,
 * and not the font file, which is software and licensed as such.
 *
 * The face is Old English Text MT rather than the design's Engravers Old
 * English BT: the same Victorian English Textura, drawn so alike that overlaid
 * at matched cap height the difference is a hair of width. Engravers is the
 * better choice if WPBrigade licenses it - point FONT at it and run this
 * again, and every heading is regenerated in it.
 *
 *   node scripts/generate-heading-outlines.js
 *   FONT=/path/to/EngraversOldEnglishBT.ttf node scripts/generate-heading-outlines.js
 */

const fs = require('fs')
const path = require('path')
const opentype = require('opentype.js')

const FONT = process.env.FONT || 'C:/Windows/Fonts/OLDENGL.TTF'
const SCHEMA = path.join(__dirname, '../src/api/achievement/content-types/achievement/schema.json')
const OUT = path.join(__dirname, '../src/utils/certificate-assets/headings.ts')

/**
 * Cap height of the traced original, measured off its "C": 24.75pt above the
 * baseline. Matching it rather than the nominal 35pt is what keeps a
 * regenerated heading the size the design was drawn at, whichever face sets
 * it - two blackletters at the same point size are not the same size on paper.
 */
const CAP_HEIGHT = 24.75

/** Where the heading's baseline sits on the source artboard. */
const BASELINE_Y = 183.618014

const font = opentype.loadSync(FONT)

const capHeightAt = (size) => -font.getPath('C', 0, 0, size).getBoundingBox().y1

let size = 35
for (let i = 0; i < 40; i += 1) size *= CAP_HEIGHT / capHeightAt(size)

const qualifiers = JSON.parse(fs.readFileSync(SCHEMA, 'utf8'))
  .attributes.certificateHeading.enum

/**
 * One heading, centred on x=0 with its baseline on y=0.
 *
 * The traced original carried the artboard's absolute coordinates and had to
 * be shifted into place by the template. Emitting it pre-centred means the
 * template translates once, to the page's centre line, and the asset needs no
 * convention to be remembered about which edge `xMin` refers to.
 */
function outline(text) {
  const advance = font.getAdvanceWidth(text, size)
  const glyphs = font.getPath(text, -advance / 2, 0, size)
  const box = glyphs.getBoundingBox()

  return {
    d: glyphs.toPathData(2),
    // Inked extent, not the advance: the text layer in the PDF is fitted to
    // this, and a trailing side bearing would push the invisible string wider
    // than the glyphs a reader sees.
    width: Number((box.x2 - box.x1).toFixed(3)),
  }
}

const entries = qualifiers.map((qualifier) => {
  const text = `Certificate of ${qualifier}`
  const { d, width } = outline(text)

  return `  ${qualifier}: {\n    text: '${text}',\n    width: ${width},\n    paths: '${d}',\n  },`
})

const source = `/**
 * The certificate's heading, as outlines, one per wording.
 *
 * GENERATED by scripts/generate-heading-outlines.js - regenerate rather than
 * hand-editing. Set in ${font.names.fullName.en} at ${size.toFixed(3)}pt, which is the
 * size at which its capitals stand ${CAP_HEIGHT}pt tall, matching the heading traced
 * from the printed design.
 *
 * Outlines rather than text because the face is licensed: it cannot be
 * embedded in what we hand out, and cannot be assumed installed wherever a
 * certificate is rendered - a PDF opened offline, a PNG built on a server.
 *
 * Each is centred on x=0 with its baseline on y=0, so placing one is a single
 * translate to the page's centre line and \`HEADING_BASELINE_Y\`.
 */

/** Where the heading's baseline sits, in the source artwork's coordinates. */
export const HEADING_BASELINE_Y = ${BASELINE_Y}

export interface Heading {
  /**
   * What the outlines say.
   *
   * Outlines carry no text - not for a PDF search, not for a screen reader.
   * This is the string the PDF's invisible text layer puts back in their
   * place; see certificate-render.ts.
   */
  text: string
  /** Inked width, for fitting that invisible string to the glyphs. */
  width: number
  paths: string
}

export const HEADINGS: Record<string, Heading> = {
${entries.join('\n')}
}
`

fs.writeFileSync(OUT, source)
console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
console.log(`  face   ${font.names.fullName.en} at ${size.toFixed(3)}pt`)
for (const q of qualifiers) console.log(`  ${String(outline(`Certificate of ${q}`).width).padStart(8)}pt  Certificate of ${q}`)
